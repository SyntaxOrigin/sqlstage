//! Entegrasyon testleri için ortak yardımcılar.
//!
//! `tempfile` crate'i bağımlılık politikasıyla yasaktır (WORKER_CONTRACT § 3.2); geçici
//! dosya yardımcısı bu yüzden kendi kodumuzla yazıldı. Testler ağ kullanmaz, sabit veri
//! kullanır ve yalnızca `std::env::temp_dir()` altına yazar.

#![allow(dead_code)]

use std::path::{Path, PathBuf};

use sqlstage::deger::Deger;
use sqlstage::yazici::TabloYazimi;

/// Test içinde geçici dosya/dizin üreten, `Drop` ile temizleyen kapsayıcı.
///
/// Neden `tempfile` yok: bağımlılık politikası (WORKER_CONTRACT § 3.2) `tempfile`'i
/// hiçbir projede vermez; yardımcı kendi kodumuzla yazılır.
pub struct GeciciDizin {
    yol: PathBuf,
}

impl GeciciDizin {
    /// `std::env::temp_dir()` altında, test adından türetilmiş benzersiz bir dizin oluşturur.
    pub fn yeni(etiket: &str) -> std::io::Result<Self> {
        let kok =
            std::env::temp_dir().join(format!("sqlstage-test{}-{etiket}", std::process::id()));
        // Aynı testin iki kez çalışması olası (yeniden deneme); içeriği temizle.
        let _ = std::fs::remove_dir_all(&kok);
        std::fs::create_dir_all(&kok)?;
        Ok(Self { yol: kok })
    }

    /// Dizin yolunu döndürür.
    pub fn yol(&self) -> &Path {
        &self.yol
    }

    /// Dizin içine göreli yol döndürür.
    pub fn dosya(&self, ad: &str) -> PathBuf {
        self.yol.join(ad)
    }
}

impl Drop for GeciciDizin {
    fn drop(&mut self) {
        // Temizlik başarısız olsa da testi düşürmemeli; `let _ =` bilinçlidir
        // (WORKER_CONTRACT § 5.3: `Drop` içinden hata döndürülemez).
        let _ = std::fs::remove_dir_all(&self.yol);
    }
}

/// Onaltılık metinden bayt dizisi üretir.
pub fn onaltilik(metin: &str) -> Vec<u8> {
    let temiz: String = metin.chars().filter(|c| !c.is_whitespace()).collect();
    let baytlar = temiz.as_bytes();
    assert!(
        baytlar.len() % 2 == 0,
        "onaltılık metin çift sayıda bayt içermeli"
    );
    baytlar
        .chunks_exact(2)
        .map(|c| {
            let yazi = std::str::from_utf8(c).unwrap_or("00");
            u8::from_str_radix(yazi, 16).unwrap_or(0)
        })
        .collect()
}

